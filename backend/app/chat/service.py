    def _last_sensor(self, state: SessionState) -> str | None:
        """The catalog sensor the student most recently talked about (their own words first, then the assistant's)."""
        for t in reversed(state.turns[-3:]):
            found = self.appkb.detect(t.user).sensors
            if found:
                return found[0]
        for t in reversed(state.turns[-1:]):
            found = self.appkb.detect(t.assistant).sensors
            if found:
                return found[0]
        return None

    def _recent_entities(self, state: SessionState) -> Entities:
        e = Entities()
        for t in state.turns[-2:]:
            e = e.merge(self.appkb.detect(f"{t.user} {t.assistant}"))
        return e

    async def _serve_app(self, p: Principal, sid: str, state: SessionState, message: str, ans: AppAnswer, base: dict,
                         page_doc: Doc | None) -> AsyncIterator[Event]:
        base = {**base, "intent": Intent.platform_faq.value, "shortcut": True, "naive_tokens": self._naive(p, page_doc, state, message)}
        yield {"type": "meta", **base}
        text = with_health_note(message, ans.text)
        out = check_output(text, source_text=text, secrets=self._secrets(p))
        for chunk in _chunks(out.text):
            yield {"type": "token", "t": chunk}
        await self._persist_turn(p, sid, state, message, out.text)
        yield self._done(base, out.text, grounded=ans.grounded and ans.kind != "not_documented", sources=ans.sources, canned=ans.kind,
                         refused_reason="not_documented" if ans.kind == "not_documented" else None, standalone_query=message,
                         connection_table=ans.table, block_stack=ans.blocks, code_blocks=ans.code, images=ans.images, footer=ans.footer, memories_used=0,
                         input_tokens=0, output_tokens=0, tokens_total=0, naive_tokens=base["naive_tokens"])

    async def _multi(self, p: Principal, parts: list[str], dropped: int, sid: str, page: str | None) -> AsyncIterator[Event]:
        """Several questions in one message: answer each one (at most MAX_PARTS) and return them together, one heading per question."""
        base: dict[str, Any] = {"session_id": sid, "intent": Intent.platform_faq.value, "router_tokens": 0}
        yield {"type": "meta", **base}
        blocks, dones = [], []
        for i, part in enumerate(parts, 1):
            done, failed = None, False
            async for ev in self._run(p, part, sid, page):
                if ev["type"] == "error":
                    failed = True   # one failed question must not hide the answers to the others
                if ev["type"] == "done":
                    done = ev
            if done is not None:
                dones.append((part, done))
                blocks.append(f"### {i}. {part[:90]}\n\n{done['answer']}")
            elif failed:
                blocks.append(f"### {i}. {part[:90]}\n\nI could not answer this one right now. Please ask it again.")
        if not dones:
            yield {"type": "error", "message": "The assistant is busy right now. Please try again."}
            return
        text = "\n\n".join(blocks) + (f"\n\nI answered the first {len(parts)} questions. Please send the others again." if dropped else "")
        warnings: list[dict] = []
        for part, d in dones:
            for w in self._safety(part, d):
                if all(w["id"] != x["id"] for x in warnings):
                    warnings.append(w)
        warnings.sort(key=lambda w: 0 if w["level"] == "danger" else 1)
        for chunk in _chunks(text):
            yield {"type": "token", "t": chunk}
        yield self._done(base, text, grounded=all(d.get("grounded") for _, d in dones),
                         sources=list(dict.fromkeys(s for _, d in dones for s in (d.get("sources") or []))),
                         code_blocks=[c for _, d in dones for c in (d.get("code_blocks") or [])], images=[i for _, d in dones for i in (d.get("images") or [])],
                         warnings=warnings[:3], input_tokens=sum(d.get("input_tokens", 0) for _, d in dones), output_tokens=sum(d.get("output_tokens", 0) for _, d in dones),
                         tokens_total=sum(d.get("tokens_total", 0) for _, d in dones), naive_tokens=sum(d.get("naive_tokens", 0) for _, d in dones),
                         standalone_query=" | ".join(parts))

    async def _general(self, p: Principal, sid: str, state: SessionState, message: str, query: str, base: dict, extra_note: str = "", system: str = GENERAL_SYSTEM, no_wiring: bool = False) -> AsyncIterator[Event]:
        """General technology/science question: model knowledge, no retrieval, no 'from the docs' claim."""
        base = {**base, "intent": Intent.general_tech.value}
        yield {"type": "meta", **base}
        app = next(iter(self.appkb.apps.values()), None) if self.appkb else None
        note = (extra_note + "\n\n" if extra_note else "") + (f"PROJECT NOTES: the student is working on '{app.title}': {app.summary}\n\n" if app else "")
        msgs: list[dict[str, str]] = [{"role": "system", "content": system + (YES_NO_HINT if _YN_START.search(message) else "")}]
        for t in state.turns[-MAX_TURNS:]:
            msgs += [{"role": "user", "content": truncate_tokens(t.user, 80)}, {"role": "assistant", "content": truncate_tokens(t.assistant, 80)}]
        msgs.append({"role": "user", "content": f"{note}QUESTION: {truncate_tokens(query, 300)}"})
        async def once(m):
            parts, fin = [], None
            async for kind, val in self.llm.answer_stream(m):
                if kind == "delta":
                    parts.append(val)
                else:
                    fin = val
            if fin:
                await self._record(p, fin.input_tokens, "answer_in")
                await self._record(p, fin.output_tokens, "answer_out")
            return fin, _CITATION.sub("", (fin.text if fin else "".join(parts)).strip())

        try:
            fin, raw = await once(msgs)
            if _REFUSAL.match(raw) and len(raw) < 160:   # the model sometimes refuses a harmless science question ("what is alcohol?"): ask once more, never show that refusal
                retry = [*msgs[:-1], {"role": "user", "content": msgs[-1]["content"] + "\n\nThis is a harmless school science question. Answer it simply, in 2 to 4 sentences."}]
                fin2, raw2 = await once(retry)
                if raw2 and not _REFUSAL.match(raw2):
                    if fin and fin2:
                        fin2 = dc_replace(fin2, input_tokens=fin.input_tokens + fin2.input_tokens, output_tokens=fin.output_tokens + fin2.output_tokens)
                    fin, raw = fin2, raw2
            raw = drop_stray_verdict(message, raw)
            if no_wiring:
                raw = strip_wiring(raw)
        except LLMError as exc:
            log.error("general_failed cause=%r", exc.__cause__)
            yield {"type": "error", "message": "The assistant is busy right now. Please try again."}
            return
        # leak/vendor checks stay on; there is no grounding check (the answer is general knowledge) and no number check
        out = check_output(raw, source_text=f"{note}{message}", secrets=self._secrets(p), min_support=0.0, numbers_source=raw)
        if out.action != "replaced" and unsupported_pins(out.text, self.app_text, message):
            out = OutputVerdict(UNVERIFIED_PIN_REPLY, "replaced", "unsupported_pin")  # general mode must not name kit pins
        blocked = out.action == "replaced"
        text = out.text if blocked else with_health_note(message, out.text)
        for chunk in _chunks(text):
            yield {"type": "token", "t": chunk}
        if not blocked:
            await self._persist_turn(p, sid, state, message, text)
        yield self._done(base, text, grounded=False, refused_reason=out.reason if blocked else None, sources=[],
                         input_tokens=fin.input_tokens if fin else 0, output_tokens=fin.output_tokens if fin else 0,
                         model=fin.model if fin else None, standalone_query=query, memories_used=0,
                         naive_tokens=self._naive(p, None, state, message),
                         tokens_total=base["router_tokens"] + (fin.input_tokens + fin.output_tokens if fin else 0))

    # ------------------------------------------------------------------ helpers
    @staticmethod
    def _is_about_focus(message: str) -> bool:
        """Does this message continue the sensor conversation ("what next?", "where does VCC go?"), or change the subject to something
        general ("which sensors can I connect?", "what is I2C?")? Only the first kind gets the sensor's name added to the search."""
        if _LIST_Q.search(message):
            return False
        if _SINGULAR_REF.search(message) or _ANAPHORA_WORD.search(message):
            return True
        if _DEFINITION.match(message) and not _WIRING.search(message):
            return False
        return len(message.split()) <= 9

    def _clarify(self, message: str, mentioned: list[str], focus: list[str]) -> str | None:
        """A question that needs a specific sensor but does not say which, and the chat gives no clue (or two clues)."""
        if not self.hw.devices or mentioned:
            return None
        if not focus and _GENERIC_ONE.search(message) and _WIRING.search(message) and not _PLURAL_OR_LIST.search(message):
            return (f"Which sensor or module do you mean? For example: {', '.join(self.hw.examples())}. "
                    f"Tell me its name and I'll explain how to connect it to the {self.hw.name}.")
        if len(focus) > 1 and _SINGULAR_REF.search(message) and _WIRING.search(message):
            names = " or ".join(self.hw.label(k) for k in focus[:3])
            return f"Do you mean the {names}? Tell me which one and I'll continue."
        return None

    async def _serve_cached(self, p, sid, state, message, hit, kind, base, page_doc: Doc | None = None) -> AsyncIterator[Event]:
        """A cache hit: 0 LLM tokens. The turn is still recorded so follow-ups keep working."""
        naive = self._naive(p, page_doc, state, message)
        for chunk in _chunks(hit.answer):
            yield {"type": "token", "t": chunk}
        await self._persist_turn(p, sid, state, message, hit.answer)
        yield self._done(base, hit.answer, grounded=True, sources=hit.sources, cache_hit=kind,
                         standalone_query=hit.question, memories_used=0, input_tokens=0, output_tokens=0,
                         tokens_total=0, naive_tokens=naive)

    async def _persist_turn(self, p: Principal, sid: str, state: SessionState, message: str, answer: str) -> None:
        """Save the turn; fold into the rolling summary lazily (only a turn that leaves the 2-turn window)."""
        state.turns.append(Turn(message, answer))
        state.history_tokens += count_tokens(message) + count_tokens(answer)
        evicted: list[Turn] = []
        if self.s.lazy_summary:
            while len(state.turns) > MAX_TURNS:
                evicted.append(state.turns.pop(0))
            await self.sessions.save(p.user_id, sid, state)
            if self.s.summary_mode == "extractive":
                for t in evicted:  # free: remember WHAT was asked; answers can always be re-retrieved
                    state.summary = fold_summary(state.summary, t.user, self.s.summary_max_tokens)
                await self.sessions.save(p.user_id, sid, state)
            else:
                for t in evicted:
                    self._spawn(self._update_summary(p, sid, t.user, t.assistant))
        else:  # legacy behaviour: summarise every turn
            await self.sessions.save(p.user_id, sid, state)
            self._spawn(self._update_summary(p, sid, message, answer))
        if self.memory and self.s.enable_long_term_memory and self.memory.should_extract(message):
            self._spawn(self._remember(p, sid, message))

    def _naive(self, p: Principal, page_doc: Doc | None, state: SessionState, message: str) -> int:
        """ESTIMATE of the input a bot WITHOUT retrieval would send for this turn. To answer anything about the
        platform it must carry every document the user can see, plus the whole chat so far, on every message.
        (Not just the open page: a bot that only saw one page could not answer questions about other lessons,
        blocks or tools.) Input only, so comparing it with our total, which includes output tokens, is conservative."""
        site = self.catalog.total_tokens(p) if self.catalog else 0
        return count_tokens(ANSWER_SYSTEM) + site + state.history_tokens + count_tokens(message) + 30

    @staticmethod
    def _secrets(p: Principal) -> list[str]:
        return [p.user_id, p.org_id, *(x for x in [p.school_id, *p.batch_ids] if x)]

    async def _my_data(self, p: Principal, message: str, summary: str, base: dict) -> AsyncIterator[Event]:
        """Live data via allow-listed read-only tools. The answer is rendered by code from tool output, so the
        model can never invent marks. Nothing from this path is written to session, summary or memory."""
        if self.adapter is None:
            yield self._done(base, MY_DATA_REPLY, grounded=False, refused_reason="my_data_unavailable")
            return
        plan = await plan_tool(self.llm, self.s, message, summary)
        await self._record(p, plan.tokens, "planner")
        if plan.tool is None:
            yield self._done(base, TOOL_HELP, grounded=False, refused_reason="no_tool")
            return
        result = await run_tool(plan.tool, plan.args, Scope.from_principal(p), self.adapter)
        log.info("tool_call tool=%s ok=%s reason=%s", plan.tool, result.ok, result.reason)  # args never logged
        out = check_output(result.text, source_text=result.text, secrets=self._secrets(p), strict_numbers=True)
        yield self._done(base, out.text, grounded=result.ok, refused_reason=None if result.ok else result.reason,
                         tool=plan.tool, router_tokens=base["router_tokens"] + plan.tokens)

    async def _update_summary(self, p: Principal, sid: str, user_msg: str, answer: str) -> None:
        """Incremental: input is the current summary + ONE turn, never the full history."""
        try:
            old = (await self.sessions.get(p.user_id, sid)).summary
            res = await self.llm.chat(
                model=self.s.router_model,
                messages=[{"role": "system", "content": SUMMARY_SYSTEM},
                          {"role": "user", "content": f"OLD SUMMARY: {old or '(none)'}\nUSER: {truncate_tokens(user_msg, 100)}\n"
                                                      f"ASSISTANT: {truncate_tokens(answer, 150)}"}],
                max_tokens=300, temperature=0,
            )
            await self._record(p, res.input_tokens + res.output_tokens, "summary")
            new = truncate_tokens(res.text.strip(), self.s.summary_max_tokens)
            if not new:
                return
            fresh = await self.sessions.get(p.user_id, sid)  # re-read: a newer turn may have been saved
            fresh.summary = new
            await self.sessions.save(p.user_id, sid, fresh)
        except Exception as exc:  # noqa: BLE001 - background; never break the chat
            log.warning("summary_update_failed %s", type(exc).__name__)

    async def _recall(self, p: Principal, vec: list[float]):
        """Long-term memory via the same query embedding. Fail-safe: memory must never break a chat."""
        if not self.memory or not self.s.enable_long_term_memory:
            return []
        try:
            return await self.memory.retrieve(vec, p)
        except Exception as exc:  # noqa: BLE001
            log.warning("memory_recall_failed %s", type(exc).__name__)
            return []

    async def _remember(self, p: Principal, sid: str, message: str) -> None:
        try:
            await self.memory.extract_and_save(p, message, sid)
        except Exception as exc:  # noqa: BLE001 - background
            log.warning("memory_save_failed %s", type(exc).__name__)

    async def _touch(self, p: Principal, ids: list[str]) -> None:
        try:
            await self.memory.store.touch(p, ids)
        except Exception as exc:  # noqa: BLE001
            log.warning("memory_touch_failed %s", type(exc).__name__)
