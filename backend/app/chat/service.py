class ChatService:
    def __init__(
        self, llm: LLMClient, retriever: HybridRetriever, sessions: SessionStore, settings: Settings,
        memory: MemoryManager | None = None, budget: TokenBudget | None = None,
        adapter: PlatformDataAdapter | None = None, cache: SemanticCache | None = None,
        tracker: UsageTracker | None = None, catalog: ContentCatalog | None = None,
    ) -> None:
        self.llm, self.retriever, self.sessions, self.s = llm, retriever, sessions, settings
        self.memory, self.budget, self.adapter, self.cache, self.tracker = memory, budget, adapter, cache, tracker
        self.catalog = catalog
        self.hw = hardware_index(settings.knowledge_dir)  # the gateway dataset: device names -> keys (inert if none)
        self.canned = CannedAnswers(self.hw) if (self.hw.devices and settings.enable_canned) else None
        self.appkb: AppKB | None = None
        self.app_text = ""
        if settings.app_knowledge_dir:  # application assistant: structured answers from backend/knowledge/ (fails loudly if invalid)
            from knowledge.loader import validate
            from knowledge.render import render_all

            kb = validate(Path(settings.app_knowledge_dir))
            self.appkb = AppKB(kb)
            self.app_text = "\n".join(sec.text for sec in render_all(kb))  # what counts as "documented" for the pin guard
        if memory is not None:
            memory.on_usage = lambda p, n: self._record(p, n, "extract")
        self._pending: set[asyncio.Task] = set()

    async def drain(self) -> None:
        """Wait for background post-processing (used by tests and on shutdown)."""
        if self._pending:
            await asyncio.gather(*self._pending, return_exceptions=True)

    def _spawn(self, coro) -> None:
        task = asyncio.create_task(coro)
        self._pending.add(task)
        task.add_done_callback(self._pending.discard)

    async def _record(self, p: Principal, tokens: int, component: str = "other") -> None:
        if self.budget:
            await self.budget.record(p, tokens)
        if self.tracker:
            await self.tracker.tokens(p, component, tokens)

    @staticmethod
    def _done(base: dict, text: str, **extra: Any) -> Event:
        extra.setdefault("tokens_total", base.get("router_tokens", 0) + extra.get("input_tokens", 0) + extra.get("output_tokens", 0))
        return {"type": "done", "answer": text, "naive_tokens": 0, **base, "sources": [], **extra}

    # ------------------------------------------------------------------ entry point (adds timing + usage log)
    async def events(self, p: Principal, message: str, session_id: str | None, page: str | None = None) -> AsyncIterator[Event]:
        t0 = time.perf_counter()
        rid = uuid.uuid4().hex
        async for ev in self._run(p, message, session_id, page):
            if ev["type"] == "done" and not ev.get("refused_reason") and "warnings" not in ev:
                ev["warnings"] = self._safety(message, ev)
            if ev["type"] in ("done", "error"):
                ev["latency_ms"] = int((time.perf_counter() - t0) * 1000)
                ev["request_id"] = rid
                if self.tracker:
                    rec = dict(ev) if ev["type"] == "done" else {"intent": "error", "refused_reason": "llm_error",
                                                                  "latency_ms": ev["latency_ms"]}
                    try:
                        rec["request_id"] = rid
                        await self.tracker.request(p, rec)
                        await self.tracker.remember_request(p, rid, rec)
                    except Exception as exc:  # noqa: BLE001 - observability must never break a chat
                        log.warning("usage_log_failed %s", type(exc).__name__)
            yield ev

    def _safety(self, message: str, ev: dict) -> list[dict]:
        """Student safety warnings for this answer: from the question, the sensors it is about (message + answer sources) and the answer text."""
        try:
            # the sensors the student NAMED; the sources of the answer count only for a follow-up ("how do I connect it?")
            follow_up = bool(_SINGULAR_REF.search(message) or re.search(r"\b(?:this|these|that|them|those|here)\b", message, re.I))
            sensors = self.appkb.detect(message + (" " + " ".join(ev.get("sources") or []) if follow_up else "")).sensors if self.appkb else []
            kind = ev.get("canned") or ("grounded" if ev.get("grounded") else None)
            return safety_warnings(message, ev.get("answer", ""), sensors, kind, ev.get("intent"))
        except Exception as exc:  # noqa: BLE001 - a warning must never break a chat
            log.warning("safety_failed %s", type(exc).__name__)
            return []

    async def _run(self, p: Principal, message: str, session_id: str | None, page: str | None = None) -> AsyncIterator[Event]:
        sid = session_id or uuid.uuid4().hex
        base: dict[str, Any] = {"session_id": sid, "intent": "blocked", "router_tokens": 0}

        # L1: deterministic input guardrails. Blocked messages cost 0 LLM tokens and touch no memory.
        verdict = check_input(message, p.role, self.s.max_message_chars)
        if not verdict.allowed:
            yield {"type": "meta", **base}
            yield self._done(base, verdict.reply or UNSAFE_REPLY, grounded=False, refused_reason=verdict.reason)
            return
        message = verdict.clean  # PII-redacted: the only form that reaches an LLM, memory, cache or logs

        if self.budget and await self.budget.exceeded(p):
            yield {"type": "meta", **base, "intent": "budget"}
            yield self._done(base, BUDGET_REPLY, grounded=False, refused_reason="budget_exceeded")
            return

        message = strip_greeting(message)   # "hello tell me about grovator" is the question "tell me about grovator"
        parts, dropped = split_questions(message)
        if len(parts) > 1:   # several questions in one message: each is answered on its own, never just the first or the wrong one
            async for ev in self._multi(p, parts, dropped, sid, page):
                yield ev
            return
        message = parts[0]

        state = await self.sessions.get(p.user_id, sid)
        had_history = bool(state.turns or state.summary)
        page_doc = None   # the open page is NOT used: the bot answers from the question and the conversation only (the `page` field is accepted and ignored)
        mentioned = self.hw.detect(message) if self.hw.devices else []
        ents, app_recent, app_ctx = Entities(), Entities(), False
        if self.appkb:
            ents, app_recent = self.appkb.detect(message), self._recent_entities(state)
            if mentioned and not ents.strong and self.appkb.claims(message, ents, app_recent):
                mentioned = []  # "LED 2", "LED 3 OFF": the lesson's LEDs, not the gateway's generic LED module
            if self.appkb.is_rewrite_request(message, ents) and not self.appkb.explain_target(message, ents, app_recent):
                # "simplify it", "explain that again", "give me an example": the PREVIOUS ANSWER reworked; never a fresh search, never the open page
                if not state.turns:
                    ask_first = AppAnswer("clarify", "Tell me what you would like me to explain or simplify. Ask a question first, then I can make it simpler, shorter or add an example.", [], grounded=False)
                    async for ev in self._serve_app(p, sid, state, message, ask_first, base, page_doc):
                        yield ev
                    return
                prev = state.turns[-1].assistant
                async for ev in self._general(p, sid, state, message, message, base, extra_note="PREVIOUS ANSWER:\n" + truncate_tokens(prev, 700) + "\n\n",
                                              system=REWRITE_SYSTEM, no_wiring=not mentions_wiring(prev)):
                    yield ev
                return
            # a general concept question ("what are pins?") names no sensor; "it" / "VCC" / "the sensor" mean the sensor the student was just talking about
            concept_q = bool(GENERAL_CUE.search(message)) and not re.search(r"\b(?:this|these|it|its|here|that one|the (?:sensor|module|device))\b", message, re.I)
            if not mentioned and not ents.strong and not concept_q and _FOLLOW_SENSOR_Q.search(message) and not re.search(r"\brules?\b|\bwhich sensors\b", message, re.I):
                last = self._last_sensor(state)
                if last:
                    ents = Entities(sensors=[last])
            simple = len(message.split()) <= 40   # a long, rambling message is not a template question: the model reads it
            ans = self.appkb.hazard_answer(message, ents) or (self.appkb.answer(message, ents, app_recent, hw_named=bool(mentioned), page_only=not mentioned) if simple else None)  # a gateway device page is open: its questions are about that device unless the application is named
            if not ans and state.turns and simple:
                ans = self.appkb.follow_up(message, state.turns[-1].user)   # "explain those blocks" after a block answer
            if ans:  # wiring tables, block order, code, thresholds, "not documented yet": built from the files, 0 tokens
                async for ev in self._serve_app(p, sid, state, message, ans, base, page_doc):
                    yield ev
                return
            app_ctx = (ents.strong or app_recent.strong or bool(ents.weak)) and not (mentioned and not ents.strong)
            target = self.appkb.explain_target(message, ents, app_recent)
            if target:   # "how does it measure / the formula / in centimetres": principle + formula + worked example, never wiring
                async for ev in self._general(p, sid, state, message, message, base, extra_note=self.appkb.explain_notes(target) + "\n\n", system=EXPLAIN_SYSTEM, no_wiring=True):
                    yield ev
                return
            if self.appkb.is_platform_question(message, ents):   # "tell me about Grovator": the platform, never the open page
                async for ev in self._general(p, sid, state, message, message, base, extra_note=PLATFORM_NOTE):
                    yield ev
                return
            if self.appkb.is_general(message, ents, bool(mentioned)) or self.appkb.is_phenomenon_question(message, ents):  # "what is SpO2?": model knowledge, simple words
                async for ev in self._general(p, sid, state, message, message, base):
                    yield ev
                return
        ask = None if app_ctx else self._clarify(message, mentioned, state.focus)
        if ask:  # ambiguous "it"/"the sensor": ask instead of guessing, 0 LLM tokens; the question is kept so the answer has context
            base = {**base, "intent": Intent.platform_faq.value, "naive_tokens": self._naive(p, None, state, message)}
            yield {"type": "meta", **base}
            await self._persist_turn(p, sid, state, message, ask)
            yield self._done(base, ask, grounded=False, refused_reason="needs_clarification",
                             naive_tokens=base["naive_tokens"], tokens_total=0)
            return
        if mentioned:
            state.focus = mentioned[:3]  # the sensor(s) now being discussed; saved with the turn
        on_device_page = False   # the open page is not used
        focus = list(state.focus)
        canned = self.canned.match(message, mentioned, focus) if self.canned else None
        if canned:
            # a plain question of a known shape: answered from the dataset by a template, no model, no search (0 tokens)
            base = {**base, "intent": Intent.platform_faq.value, "shortcut": True, "naive_tokens": self._naive(p, page_doc, state, message)}
            yield {"type": "meta", **base}
            out = check_output(canned.text, source_text=canned.text, secrets=self._secrets(p))
            for chunk in _chunks(out.text):
                yield {"type": "token", "t": chunk}
            await self._persist_turn(p, sid, state, message, out.text)
            yield self._done(base, out.text, grounded=True, sources=canned.sources, canned=canned.kind, standalone_query=message,
                             memories_used=0, input_tokens=0, output_tokens=0, tokens_total=0, naive_tokens=base["naive_tokens"])
            return
        # the answer to "Which sensor do you mean?" is just a name ("for alcohol sensor"): the real question is the one before it
        answers_clarification = bool(mentioned and state.turns and state.turns[-1].assistant.startswith(_CLARIFY_STARTS)
                                     and len(message.split()) <= 5)
        use_cache = self.cache is not None and self.s.enable_semantic_cache
        # The page the user is reading (only if they may see it; unknown and hidden pages are treated the same).
        naive0 = self._naive(p, page_doc, state, message)  # what a bot without retrieval would send for this message
        version = f"{self.retriever.version}:{page_doc.source if page_doc else '-'}"  # answers are page-specific
        qvec: list[float] | None = None
        checked_vec_for: str | None = None

        # L2a: a first message is standalone by definition, so it can be matched before the router runs.
        pre_text = f"{page_doc.title}: {message}" if (page_doc and DEICTIC.search(message)) else message
        if use_cache and not had_history:
            qvec = await embed_query(pre_text)
            hit = await self.cache.lookup(p, qvec, version)
            checked_vec_for = message
            if hit:
                base = {**base, "intent": Intent.platform_faq.value}
                yield {"type": "meta", **base}
                async for ev in self._serve_cached(p, sid, state, message, hit, "pre_router", base, page_doc):
                    yield ev
                return

        # L3: free shortcut for obvious cases, otherwise one small-model call.
        route = (try_shortcut(message, bool(state.turns), state.turns[-1].user if state.turns else "", on_page=page_doc is not None)
                 if self.s.enable_router_shortcut else None)
        if route is None:
            recent = [t.user for t in state.turns[-2:]] if self.s.lazy_summary else [t.user for t in state.turns[-1:]]
            route = await route_message(self.llm, self.s, state.summary, recent, message)
            await self._record(p, route.input_tokens + route.output_tokens, "router")
            if route.intent is Intent.my_data and not looks_like_data_request(message):
                # the small router is not trusted to start a data lookup on its own (it slipped on "can I get a deleted one back?")
                route = dc_replace(route, intent=Intent.platform_faq, query=route.query or message)
        base = {"session_id": sid, "intent": route.intent.value, "router_tokens": route.input_tokens + route.output_tokens,
                "shortcut": route.shortcut, "naive_tokens": naive0}
        yield {"type": "meta", **base}

        canned = {Intent.unsafe: (UNSAFE_REPLY, "unsafe"), Intent.off_topic: (OFF_TOPIC_REPLY, "off_topic")}
        if route.intent in canned:
            text, reason = canned[route.intent]
            yield self._done(base, text, grounded=False, refused_reason=reason)
            return
        if route.intent is Intent.general_tech:
            async for ev in self._general(p, sid, state, message, route.query, base):
                yield ev
            return
        if route.intent is Intent.smalltalk:
            # Greetings, thanks and "how are you" are answered by free canned rules (route.shortcut). Anything else the router
            # calls smalltalk ("what do you like to eat?") gets a fixed redirect: a model must never free-write small talk,
            # because it invents a personality ("I love pizza!").
            reply = (route.reply or SMALLTALK_FALLBACK) if route.shortcut else REDIRECT_REPLY
            out = check_output(reply, source_text=reply, secrets=self._secrets(p))  # smalltalk still gets leak/vendor checks
            yield self._done(base, out.text, grounded=False)
            return
        if route.intent is Intent.my_data:
            async for ev in self._my_data(p, message, state.summary, base):
                yield ev
            return

        # platform_faq: retrieval always runs on the standalone (rewritten) query.
        # Scope comes from the JWT principal only; the LLM never chooses whose data to fetch.
        glued = route.shortcut and route.query != message
        # "explain THESE rules" on the open Wiring Rules page is about that page, not about the sensor discussed earlier
        page_wins = bool(page_doc and DEICTIC.search(message) and not on_device_page and not mentioned)
        if self.hw.devices and focus and not page_wins and (mentioned or self._is_about_focus(message)):
            # keep the sensor in every search: a follow-up that does not name it ("what should I do after connecting it?") must still
            # find ITS page, not a similar page of another sensor. (Replaces the free "previous question + message" glue.)
            labels = " and ".join(self.hw.label(k) for k in focus)
            base_q = message if route.shortcut else route.query
            if answers_clarification:
                base_q = f"{state.turns[-1].user} {message}"
            route = dc_replace(route, query=base_q if labels.lower() in base_q.lower() else f"{base_q} ({labels})")
            glued = False
        if app_ctx and not mentioned and self.appkb:
            label = self.appkb.app_label(ents.merge(app_recent))  # "what about the LED?" -> about the pulse oximeter project
            if label and label.lower() not in route.query.lower():
                route = dc_replace(route, query=f"{route.query} ({label})")
        query = route.query
        points_at_page = bool(page_doc and DEICTIC.search(message))
        if points_at_page:
            query = f"{page_doc.title}: {route.query}"  # make "explain this" searchable: add what "this" is
        vec = qvec if (qvec is not None and query == pre_text) else await embed_query(query)
        if use_cache and self.s.cache_followups and checked_vec_for != route.query:  # L2b (opt-in): rewritten follow-ups
            hit = await self.cache.lookup(p, vec, version)
            if hit:
                async for ev in self._serve_cached(p, sid, state, message, hit, "post_router", base, page_doc):
                    yield ev
                return

        # a free follow-up rewrite glues the previous question on: also search the NEW message on its own
        also = [(message, await embed_query(message))] if (glued and not points_at_page) else None
        pins = _PIN_IN_TEXT.findall(message) if self.hw.devices else []
        if pins:
            # a GPIO the student names ("can I use GPIO21?") must find the page that says what that pin is for (e.g. the I2C interface)
            pin_text = f"{' '.join(pins)} pin function on the gateway"
            also = [*(also or []), (pin_text, await embed_query(pin_text))]
        if self.hw.devices and not mentioned and _LIST_Q.search(message):
            # "which sensors can I connect?": the answer is the gateway overview (every device and interface), not the few device pages
            # that happen to match the words best
            ov = f"About the {self.hw.name}: sensors, actuators and modules the gateway documents; interfaces on the gateway. {message}"
            also = [*(also or []), (ov, await embed_query(ov))]
        asks_order = bool(SEQUENCE_Q.search(message)) and not self.hw.devices  # lesson-order questions only exist with lesson content
        if asks_order:
            # a question about lesson ORDER: also search the learning path / previous-and-next sections, otherwise pages that merely
            # mention the named lesson ("move and turn") crowd the answer out
            seq_text = f"Learning Path lesson order, previous lesson and next lesson: {route.query}"
            also = [*(also or []), (seq_text, await embed_query(seq_text))]
        direct = bool(self.hw.devices and focus and not pins and not asks_order and not page_wins
                      and (mentioned or self._is_about_focus(message)) and not _LIST_Q.search(message))
        reuse = False
        if direct:
            # the device is known: read ITS guide (best 2 sections per device), do not search the whole knowledge base
            asked = f"{state.turns[-1].user} {message}" if answers_clarification else message
            prefer = [h for rx, h in _SECTION_INTENTS if rx.search(asked)]
            dkey = f"{self.retriever.version}:dev:{'+'.join(focus[:2])}:{'/'.join(prefer[:2])}"
            reuse = use_cache and not _SPECIFIC.search(asked)
            if reuse:
                # the same question about the same device and section, from any student: a verified answer costs 0 tokens
                hit = await self.cache.lookup(p, vec, dkey)
                if hit and _salient(hit.question) == _salient(route.query):
                    async for ev in self._serve_cached(p, sid, state, message, hit, "direct", base, page_doc):
                        yield ev
                    return
            srcs = [f"devices/{k}" for k in focus[:2]]
            if _DEFINITION.match(message) and not _WIRING.search(message):
                # "what is a buzzer": the concept (glossary) comes with the device guide; the guide alone only says how to wire it
                srcs.append("concepts/glossary")
                prefer = ["About", *prefer]
            res = await self.retriever.retrieve_from(srcs, p, vec, per_source=2, prefer=prefer)
        else:
            res = await self.retriever.retrieve(query, p, k=min(6, self.s.knowledge_top_k + max(0, len(focus) - 1) * 2), vec=vec, also=also,
                                                pin_source=page_doc.source if page_doc else None, pin_first=points_at_page)
        naive = self._naive(p, page_doc, state, message)
        if not res.hits or res.confidence < self.s.min_retrieval_score:
            yield self._done(base, NO_INFO_REPLY, grounded=False, refused_reason="low_confidence",
                             tokens_total=base["router_tokens"], naive_tokens=naive)
            return

        # Sentence-level compression keeps only the best sentences, which truncates a LIST the user asked for in full ("in what
        # order..."): order questions get whole chunks. The token budget in build_context still applies.
        hits = (await compress_hits(res.hits, [res.vec, *(v for _, v in (also or []))], self.s)
                if self.s.enable_compression and not asks_order and not self.hw.devices else res.hits)
        mems = await self._recall(p, res.vec)
        messages, used = build_answer_messages(
            # a direct lookup is self-contained: the question carries the device name and the context is that device's guide, so the
            # chat history adds tokens but no information (and leaving it out makes the answer reusable across students)
            summary="" if direct else state.summary, turns=[] if direct else state.turns, hits=hits,
            question=route.query if direct else message,
            memories=[m.text for m in mems], memory_cap=self.s.memory_prompt_tokens,
            total_budget=self.s.answer_total_budget, context_cap=self.s.context_token_budget,
            system_hint=YES_NO_HINT if _YN_START.search(message) else "",
        )
        async def generate(msgs):
            parts, fin = [], None
            # Consume the model stream server-side. NOTHING is sent to the client until the output guard has
            # approved the full text, so a leak can never reach the wire (see DECISIONS D31).
            async for kind, val in self.llm.answer_stream(msgs):
                if kind == "delta":
                    parts.append(val)
                else:
                    fin = val
            if fin:
                await self._record(p, fin.input_tokens, "answer_in")
                await self._record(p, fin.output_tokens, "answer_out")
            return (fin.text if fin else "".join(parts)).strip(), fin

        try:
            raw, final = await generate(messages)
        except LLMError as exc:
            log.error("answer_failed cause=%r", exc.__cause__)
            yield {"type": "error", "message": "The assistant is busy right now. Please try again."}
            return
        raw = drop_stray_verdict(message, _CITATION.sub("", raw))  # the model sometimes emits fake citation markers; no "Yes." on a "what is" question

        # L7: authoritative output check on the full text. Context = what the model was legitimately given.
        source = "\n".join([*(h.text for h in used), message, state.summary,
                            *(f"{t.user} {t.assistant}" for t in state.turns)])
        full_knowledge = "\n".join(h.text for h in res.hits)  # uncompressed: numbers from dropped sentences are still knowledge

        def verdict(text):
            o = check_output(text, source_text=source, secrets=self._secrets(p), min_support=self.s.grounding_min_support,
                             numbers_source=source + "\n" + full_knowledge)
            bad = unsupported_pins(o.text, full_knowledge, message) if (o.action != "replaced" and self.hw.devices) else []
            return o, bad

        out, bad_pins = verdict(raw)
        if bad_pins:
            # an invented pin ("e.g. GPIO15") is never shown. One strict retry; if it still invents, a fixed safe reply.
            log.warning("unsupported_pin_retry n=%d", len(bad_pins))
            strict = [*messages[:-1], {"role": "user", "content": messages[-1]["content"] +
                      "\n\nDo not name any GPIO number that is not written in the CONTEXT. Do not give examples. If a pin is not documented, say so."}]
            try:
                raw2, final2 = await generate(strict)
                if final and final2:
                    final = dc_replace(final2, input_tokens=final.input_tokens + final2.input_tokens,
                                       output_tokens=final.output_tokens + final2.output_tokens)
                out, bad_pins = verdict(_CITATION.sub("", raw2))
            except LLMError:
                pass
        if bad_pins:
            out = OutputVerdict(UNVERIFIED_PIN_REPLY, "replaced", "unsupported_pin")
        if out.action != "replaced":
            out = OutputVerdict(with_health_note(message, out.text), out.action, out.reason)
        for chunk in _chunks(out.text):
            yield {"type": "token", "t": chunk}
        answer = out.text
        blocked = out.action == "replaced"
        sources = [] if blocked else cited_sources(answer, used)
        truncated = bool(final and final.finish_reason == "length")

        if not blocked:  # never persist a blocked answer into context, summary, memory or cache
            await self._persist_turn(p, sid, state, message, answer)
            if use_cache and not mems and not truncated and out.action == "pass" and cacheable(message, answer):
                if direct and reuse:
                    await self.cache.store(p, vec, route.query, answer, sources, dkey)
                elif not direct and not had_history:
                    await self.cache.store(p, vec, route.query, answer, sources, version)
        if mems:
            self._spawn(self._touch(p, [m.id for m in mems]))
        yield self._done(
            base, answer, grounded=not blocked, refused_reason=out.reason if blocked else None, sources=sources,
            input_tokens=final.input_tokens if final else 0, output_tokens=final.output_tokens if final else 0,
            model=final.model if final else None, truncated=truncated,
            images=(self.appkb.images_for([h.source for h in used[:1]]) if (self.appkb and self.appkb.about_lesson(ents) and not blocked) else []),  # only when the question is about the application
            standalone_query=route.query, memories_used=len(mems), naive_tokens=naive,
            tokens_total=base["router_tokens"] + (final.input_tokens + final.output_tokens if final else 0),
        )

