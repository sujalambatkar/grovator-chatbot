def _chunks(text: str, words: int = 3) -> list[str]:
    """Re-chunk verified text so the client still gets a typing effect."""
    parts = re.findall(r"\S+\s*", text)
    return ["".join(parts[i : i + words]) for i in range(0, len(parts), words)]


